# Arithmetic Operators

#   +    --- addition sign (plus)
#   -    --- subtraction sign (minus)
#   *    --- multiplication sign 
#   /    --- division sign

#   **   --- power sign
#   //   --- floor division sign (removes the decimal part)

#   =    --- equal sign (used in variables.)


print(5+5)
print(10-2)
print(3*5)
print(7/2)

print(5**2)
print(5**3)

print(7//2)
print(9//4)





# COMPARISON OPERATORS  (used for checking)


#    >    --- greater than sign (used to check if the first value is greater than the second value)
#    <    --- less than sign (used to check if the first value is less than the second value)

#    >=   --- greater than or equal to sign (used to check if the first value is greater than or equal to the second value)
#    <=   --- less than or equal to sign (used to check if the first value is less than or equal to the second value)

#    ==   --- equal to sign (used to check if the first value is equal to the second value)




print(5 > 2)

print(10 > 20)

print(3 < 5)

print(7 < 2)





print(10 >= 10)
print(15 >= 16)

print(5 <= 10)

print(5 <= 3)

print(5 <= 5)

print(10 == 5)

print(10 == 10)




