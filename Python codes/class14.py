# Horse riding with if-else statements
# Suppose we went to a horse riding academy
# There is a condition on horse riding based on age
# - If your age is greater than or equal to 13, you can ride the horse
# - Otherwise, you cannot ride the horse


age = 15


if age >= 13:
    print("You can ride the horse")

else:
    print("Sorry! You cannot ride the horse.")






